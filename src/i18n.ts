const STORAGE_KEY = "acl.locale";

function detectLocale(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY) as Locale | null;
    if (saved && LOCALES.some((l) => l.id === saved)) return saved;
    const nav = (navigator.language || "zh").toLowerCase();
    const hit = LOCALES.find((l) => nav.startsWith(l.id));
    if (hit) return hit.id;
  } catch {
    /* ignore */
  }
  return "zh";
}

export const locale = ref<Locale>(detectLocale());

export function setLocale(id: Locale) {
  locale.value = id;
  try {
    localStorage.setItem(STORAGE_KEY, id);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = id;
}

/** 取一条界面文案，`{name}` 形式占位符会被 `vars` 替换。 */
export function t(key: string, vars?: Record<string, string | number>): string {
  const msg = MESSAGES[key];
  let text = msg ? msg[locale.value] || msg.en : key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.split(`{${k}}`).join(String(v));
    }
  }
  return text;
}

